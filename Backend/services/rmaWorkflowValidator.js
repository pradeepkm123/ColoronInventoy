const validateTransition = (fromStatus, toStatus, isSuperAdmin = false) => {
  if (!fromStatus) return { valid: true };
  if (fromStatus === toStatus) return { valid: true };

  // Super Admin can override with reason
  if (isSuperAdmin) {
    return { valid: true, overridden: true };
  }

  const allowed = ALLOWED_TRANSITIONS[fromStatus] || [];
  if (!allowed.includes(toStatus)) {
    return {
      valid: false,
      message: `Invalid RMA status transition from '${fromStatus}' to '${toStatus}'. Allowed transitions: ${allowed.join(', ') || 'None'}`,
    };
  }

  return { valid: true };
};

module.exports = {
  ALLOWED_TRANSITIONS,
  validateTransition,
};
